#!/usr/bin/env python3
"""Generate the Bubble -> Supabase sync migration from supabase/bubble_map.json.

Usage: python3 scripts/gen_sync.py
Writes supabase/migrations/20261114000003_sync.sql
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import gen_schema as g  # noqa: E402

# Types that change often are fetched every 10 minutes, the rest hourly.
FAST = {"user", "shift", "availability", "progress_notes", "message", "thread",
        "shift_logs", "invoice", "event"}


def rule(display: str) -> str:
    n = g.snake(display)
    if n in g.RESERVED:
        n += "_value"
    if n in g.SYSTEM_COLS:
        n = "id_document" if n == "id" else n + "_field"
    return n


def main():
    m = json.loads((ROOT / "supabase" / "bubble_map.json").read_text())
    types, opts, exc = {}, {}, {}
    for btype, t in m["tables"].items():
        api_path = t["display"].lower().replace(" ", "")
        types[btype] = [api_path, t["table"], 10 if btype in FAST else 60]
        for f in t["fields"].values():
            if f["type"].startswith("option.") or f["type"].startswith("list.option."):
                opts.setdefault(t["table"], {})[f["column"]] = f["type"].split("option.", 1)[1]
            if rule(f["display"]) != f["column"]:
                exc.setdefault(t["table"], {})[f["display"]] = f["column"]
    joins = [[j["bubble_type"], j["display"], j["table"], j["owner_col"], j["target_col"], j["target_table"]]
             for j in m["joins"]]
    cfg = json.dumps({"types": types, "opts": opts, "exc": exc, "joins": joins},
                     separators=(",", ":"))
    reserved = ",".join(f"'{w}'" for w in sorted(g.RESERVED))

    sql = TEMPLATE.replace("__RESERVED__", reserved).replace("__CONFIG__", cfg)
    out = ROOT / "supabase" / "migrations" / "20261114000003_sync.sql"
    out.write_text(sql)
    print(f"wrote {out.name} ({len(sql)} bytes)")


TEMPLATE = r"""-- One-way sync: Bubble Data API -> sync.bubble_raw -> app tables.
-- Generated by scripts/gen_sync.py. The edge function bubble-sync fills
-- sync.bubble_raw; sync.apply_bubble() turns raw rows into app rows.
-- App ids are md5(bubble_id) so references resolve without lookups.

create schema if not exists sync;

-- Keep Bubble's Modified Date when the sync sets updated_at explicitly.
create or replace function app.set_updated_at() returns trigger language plpgsql as $$
begin
  if new.updated_at is not distinct from old.updated_at then
    new.updated_at = now();
  end if;
  return new;
end $$;

create table sync.bubble_raw (
  bubble_id text primary key,
  type text not null,
  data jsonb not null,
  modified_at timestamptz,
  fetched_at timestamptz not null default now(),
  applied_at timestamptz,
  error text
);
create index bubble_raw_pending_idx on sync.bubble_raw (type) where applied_at is null;

create table sync.types (
  bubble_type text primary key,
  api_path text not null unique,
  app_table text not null,
  every_minutes int not null,
  enabled boolean not null default true,
  watermark timestamptz,
  backlog boolean not null default true,
  last_run timestamptz,
  last_error text
);

create table sync.config (key text primary key, value jsonb not null);

create table sync.lock (id int primary key, running_until timestamptz);
insert into sync.lock values (1, null);

create table sync.runs (
  id bigserial primary key,
  kind text not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  rows int,
  detail jsonb
);

alter table sync.bubble_raw enable row level security;
alter table sync.types enable row level security;
alter table sync.config enable row level security;
alter table sync.lock enable row level security;
alter table sync.runs enable row level security;

insert into sync.config values ('map', $cfg$__CONFIG__$cfg$::jsonb);

insert into sync.types (bubble_type, api_path, app_table, every_minutes)
select key, value->>0, value->>1, (value->>2)::int
from jsonb_each((select value->'types' from sync.config where key = 'map'));

-- Helpers ------------------------------------------------------------------

create or replace function sync.bid_uuid(p text) returns uuid
language sql immutable as $$ select md5(p)::uuid $$;

-- Same naming rule as scripts/gen_schema.py col_name().
create or replace function sync.norm_key(p text) returns text
language plpgsql immutable as $$
declare n text;
begin
  n := lower(trim(both '_' from regexp_replace(p, '[^a-zA-Z0-9]+', '_', 'g')));
  if n = '' then n := 'field'; end if;
  if n ~ '^[0-9]' then n := 'f_' || n; end if;
  if n = any (array[__RESERVED__]) then n := n || '_value'; end if;
  if n = 'id' then n := 'id_document';
  elsif n in ('bubble_id', 'created_at', 'updated_at', 'created_by') then n := n || '_field';
  end if;
  return n;
end $$;

create or replace function sync.fix_url(v jsonb) returns jsonb
language sql immutable as $$
  select case
    when jsonb_typeof(v) = 'string' and v #>> '{}' like '//%' then to_jsonb('https:' || (v #>> '{}'))
    when jsonb_typeof(v) = 'array' then coalesce((select jsonb_agg(sync.fix_url(e)) from jsonb_array_elements(v) e), '[]'::jsonb)
    else v end
$$;

create or replace function sync.opt(p_set text, v jsonb) returns jsonb
language sql stable as $$
  select case
    when jsonb_typeof(v) = 'array' then coalesce((select jsonb_agg(sync.opt(p_set, e)) from jsonb_array_elements(v) e), '[]'::jsonb)
    when jsonb_typeof(v) = 'string' then to_jsonb(coalesce(
      (select o.value from app.option_values o where o.set_key = p_set and o.display = v #>> '{}' limit 1),
      v #>> '{}'))
    else v end
$$;

-- Turn one Bubble object into a jsonb row shaped like its app table.
-- Reference columns (p_refcols) get md5 ids; apply_bubble() checks they exist.
create or replace function sync.to_row(p_table text, p_bubble_id text, d jsonb, p_refcols text[]) returns jsonb
language plpgsql stable as $$
declare
  cfg jsonb := (select value from sync.config where key = 'map');
  exc jsonb := coalesce(cfg->'exc'->p_table, '{}');
  opts jsonb := coalesce(cfg->'opts'->p_table, '{}');
  out jsonb := '{}';
  k text; v jsonb; col text;
begin
  for k, v in select * from jsonb_each(d) loop
    if k in ('_id', 'Created Date', 'Modified Date', 'Created By', 'Slug', 'authentication', 'user_signed_up') then
      continue;
    end if;
    col := coalesce(exc->>k, sync.norm_key(k));
    if opts ? col then
      v := sync.opt(opts->>col, v);
    end if;
    if col = any (p_refcols) then
      v := case when jsonb_typeof(v) = 'string' then to_jsonb(sync.bid_uuid(v #>> '{}')) else 'null'::jsonb end;
    else
      v := sync.fix_url(v);
    end if;
    out := out || jsonb_build_object(col, v);
  end loop;
  out := out || jsonb_build_object(
    'id', sync.bid_uuid(p_bubble_id),
    'bubble_id', p_bubble_id,
    'created_at', coalesce(d->>'Created Date', now()::text),
    'updated_at', coalesce(d->>'Modified Date', now()::text),
    'created_by', case when d ? 'Created By' then sync.bid_uuid(d->>'Created By') end);
  if p_table = 'users' then
    out := out || jsonb_build_object('email', lower(d->'authentication'->'email'->>'email'));
  end if;
  return out;
end $$;

-- Apply every pending raw row to the app tables. Safe to run repeatedly.
-- Pass 1 writes rows without references, pass 2 fills references that
-- point at rows that exist, so arrival order never matters.
create or replace function sync.apply_bubble() returns int
language plpgsql security definer set search_path = '' as $$
declare
  cfg jsonb := (select value from sync.config where key = 'map');
  t record; j jsonb; r record;
  cols text; sets text; refcols text[]; refset text;
  n int := 0; run_id bigint;
begin
  insert into sync.runs (kind) values ('apply') returning id into run_id;

  for t in select bubble_type, app_table from sync.types loop
    if not exists (select 1 from sync.bubble_raw where type = t.bubble_type and applied_at is null) then
      continue;
    end if;
    select string_agg(quote_ident(column_name), ', '),
           string_agg(format('%1$I = excluded.%1$I', column_name), ', ') filter (where column_name not in ('id', 'created_at'))
      into cols, sets
      from information_schema.columns where table_schema = 'app' and table_name = t.app_table;
    select coalesce(array_agg(a.attname::text), '{}') into refcols
      from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
     where c.conrelid = format('app.%I', t.app_table)::regclass and c.contype = 'f'
       and a.attname not in ('auth_user_id');

    for r in select bubble_id, data from sync.bubble_raw
              where type = t.bubble_type and applied_at is null loop
      begin
        execute format(
          'insert into app.%1$I (%2$s) select %2$s from jsonb_populate_record(null::app.%1$I, $1) on conflict (id) do update set %3$s',
          t.app_table, cols, sets)
        using sync.to_row(t.app_table, r.bubble_id, r.data, refcols) - refcols;
        update sync.bubble_raw set applied_at = now(), error = null where bubble_id = r.bubble_id;
        n := n + 1;
      exception when others then
        update sync.bubble_raw set error = sqlerrm where bubble_id = r.bubble_id;
      end;
    end loop;
  end loop;

  -- Pass 2: references.
  for t in select bubble_type, app_table from sync.types loop
    select string_agg(format('%1$I = (select y.id from %2$s y where y.id = r.%1$I)', a.attname, c.confrelid::regclass), ', '),
           coalesce(array_agg(a.attname::text), '{}')
      into refset, refcols
      from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
     where c.conrelid = format('app.%I', t.app_table)::regclass and c.contype = 'f'
       and a.attname not in ('auth_user_id');
    if refset is null then continue; end if;
    for r in select bubble_id, data from sync.bubble_raw
              where type = t.bubble_type and applied_at = now() loop
      execute format(
        'update app.%1$I x set %2$s from jsonb_populate_record(null::app.%1$I, $1) r where x.id = r.id',
        t.app_table, refset)
      using sync.to_row(t.app_table, r.bubble_id, r.data, refcols);
    end loop;
  end loop;

  -- Join tables: replace each applied owner's list.
  for j in select value from jsonb_array_elements(cfg->'joins') loop
    execute format(
      'delete from app.%1$I x using sync.bubble_raw b
        where b.type = %2$L and b.applied_at = now() and x.%3$I = sync.bid_uuid(b.bubble_id)',
      j->>2, j->>0, j->>3);
    execute format(
      'insert into app.%1$I (%3$I, %4$I)
       select distinct sync.bid_uuid(b.bubble_id), sync.bid_uuid(e)
         from sync.bubble_raw b
         cross join lateral jsonb_array_elements_text(
           case when jsonb_typeof(b.data->%5$L) = ''array'' then b.data->%5$L else ''[]''::jsonb end) e
        where b.type = %2$L and b.applied_at = now()
          and exists (select 1 from app.%6$I t where t.id = sync.bid_uuid(e))
       on conflict do nothing',
      j->>2, j->>0, j->>3, j->>4, j->>1, j->>5);
  end loop;

  update sync.runs set finished_at = now(), rows = n where id = run_id;
  return n;
end $$;

revoke all on all functions in schema sync from public;
"""

if __name__ == "__main__":
    main()
